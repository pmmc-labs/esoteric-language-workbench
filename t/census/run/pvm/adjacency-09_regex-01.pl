use v5.42;
my $s = "abcd";
my $p = "b";
my $hit = $s =~ /abc/;
my $miss = $s !~ m{zzz};
my $bang = $s =~ m!abc!;
my $hash = $s =~ m#abc#;
my $nest = "a{b}c" =~ m{a{b}c};
my $interp = $s =~ /$p/;
my $re = qr/abc/;
$s =~ s{a}{z};
$s =~ s/c/y/;
$s =~ s#d#w#;
my $n = "a{b}c";
$n =~ s{a{b}c}{ok};
my $tr = "a.c";
my $cnt = ($tr =~ tr/./Z/);
my @f = split / /, "p q";
my $pos = "abcabc";
$pos =~ m/b/g;
my $at = pos($pos);
print "$hit $miss $bang $hash $nest $interp $re $s $n $tr $cnt @f $at\n";
