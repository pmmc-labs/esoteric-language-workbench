# The assigning operators, each on a variable that holds something and,
# where perl is silent about it, on one that holds nothing (D56). The
# value of each is the variable, afterwards.
use v5.42;
my $n = 7;
say $n += 3;
say $n -= 4;
say $n *= 5;
say $n /= 4;
say $n **= 2;
say $n %= 10;
say $n x= 3;
say $n .= "!";
say $n;
my $a1;
say $a1 += 5;
my $a2;
say $a2 -= 5;
my $a3;
say $a3 .= "tail";
my $a4;
say $a4 ||= "or";
say $a4 ||= "not this";
my $a5;
say $a5 //= 0;
say $a5 //= 9;
say $a5 ||= "zero is false";
my $a6;
say defined($a6 &&= 5) ? "defined" : "undef";
$a6 = 3;
say $a6 &&= 5;
say $a6 &&= 0;
say $a6 &&= 9;
my $b1 += 2;
say $b1;
my $b2 .= "new";
say $b2;
my $b3 ||= "fresh";
say $b3;
my $b4 //= "fresher";
say $b4;
my $b5 -= 2;
say $b5;
my $t = true;
$t += 1;
say $t;
$t = false;
$t .= "|";
say $t;
my $s = "5";
$s += 1;
say $s;
$s = "5";
$s .= 1;
say $s;
$s x= 2;
say $s;
$s = 1.5;
$s *= 2;
say $s;
$s /= 2;
say $s;
$s -= 0.5;
say $s;
my $k = 10;
$k -= $k;
say $k;
$k += $k += 3;
say $k;
$k = 2;
$k **= $k;
say $k;
$k .= $k;
say $k;
$k = 3;
$k *= $k + 1;
say $k;
$k ||= $k++;
say $k;
$k = 0;
$k ||= ++$k;
say $k;
$k = 4;
$k = $k++ + $k;
say $k;
$k = 4;
$k = $k + $k++;
say $k;
$k = 4;
$k = ++$k + $k++;
say $k;
$k = 4;
$k += $k++;
say $k;
$k = 4;
$k -= ++$k;
say $k;
