"""Model for step 9's in-place updates (D48): random programs that mix
aliasing (`let`, `=`, arguments, storing, returning, `for` snapshots) with
updates that the runtime may now do in place, so any update that leaks
through an alias shows as a difference. The definition is D7's: every
assignment, argument and store is a copy, which this model does with
Python's copy.deepcopy. Ditto's printed form for lists and maps of ints
and strings is Python's repr with double quotes.

    python3 t/models/inplace.py --program 1 > t/900-inplace-random-1.ditto
    python3 t/models/inplace.py --expected 1 > t/900-inplace-random-1.expected
    python3 t/models/inplace.py --program 2 > t/901-inplace-random-2.ditto
    python3 t/models/inplace.py --expected 2 > t/901-inplace-random-2.expected
    python3 t/models/inplace.py --program 3 > t/902-inplace-random-3.ditto
    python3 t/models/inplace.py --expected 3 > t/902-inplace-random-3.expected
"""
import copy
import random
import sys

VARS = ['a', 'b', 'c']


def show(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return '"' + v + '"'
    if isinstance(v, list):
        return '[' + ', '.join(show(x) for x in v) + ']'
    return '{' + ', '.join(show(k) + ': ' + show(x) for k, x in v.items()) + '}'


def gen(seed):
    """Returns (program lines, expected lines)."""
    rng = random.Random(seed)
    env = {'a': [1, 2], 'b': [3], 'c': [4, 5, 6], 'm': {'x': 1}}
    prog = ['// Generated by t/models/inplace.py: aliasing mixed with updates (D48).',
            'fn bump(xs, k) {',
            '  xs[0] += k',
            '  xs += [k]',
            '  return xs',
            '}',
            'fn touch(m, k) {',
            '  m.x += k',
            '  m["k{k}"] = k',
            '  return len(m)',
            '}',
            'let a = [1, 2]', 'let b = [3]', 'let c = [4, 5, 6]', 'let m = {x: 1}',
            'let saved = []']
    env['saved'] = []
    out = []

    def bump(xs, k):
        xs = copy.deepcopy(xs)
        xs[0] += k
        xs += [k]
        return xs

    for step in range(120):
        v, w = rng.choice(VARS), rng.choice(VARS)
        k = rng.randint(1, 9)
        op = rng.randrange(12)
        if op == 0:
            prog.append(f'{v} = {w}')
            env[v] = copy.deepcopy(env[w])
        elif op == 1:
            n = len(env[v])
            prog.append(f'{v}[{k} % len({v})] = {k * 10}')
            env[v][k % n] = k * 10
        elif op == 2:
            prog.append(f'{v} += [{k}]')
            env[v] = env[v] + [k]
        elif op == 3:
            prog.append(f'{v} += {w}')
            env[v] = env[v] + copy.deepcopy(env[w])
        elif op == 4:
            prog.append(f'{v} = bump({w}, {k})')
            env[v] = bump(env[w], k)
        elif op == 5:
            prog.append(f'let r{step} = bump({v}, {k})')
            prog.append(f'print(r{step}, {v})')
            out.append(show(bump(env[v], k)) + ' ' + show(env[v]))
        elif op == 6:
            prog.append(f'for x in {v} {{ {v} += [x]; {v}[0] = x }}')
            snap = copy.deepcopy(env[v])
            for x in snap:
                env[v] = env[v] + [x]
                env[v][0] = x
        elif op == 7:
            prog.append(f'saved += [{v}]')
            prog.append(f'{v}[0] = {k}')
            env['saved'] = env['saved'] + [copy.deepcopy(env[v])]
            env[v][0] = k
        elif op == 8:
            prog.append(f'm["{v}"] = {v}')
            prog.append(f'm.x += {k}')
            env['m'][v] = copy.deepcopy(env[v])
            env['m']['x'] += k
        elif op == 9:
            prog.append(f'print(touch(m, {k}), m)')
            mm = copy.deepcopy(env['m'])
            mm['x'] += k
            mm[f'k{k}'] = k
            out.append(show(len(mm)) + ' ' + show(env['m']))
        elif op == 10:
            prog.append(f'if len({v}) > 12 {{ {v} = slice({v}, len({v}) - 5, len({v})) }}')
            if len(env[v]) > 12:
                env[v] = env[v][-5:]
        else:
            prog.append(f'print({v}, {w}, {v} == {w})')
            out.append(f'{show(env[v])} {show(env[w])} {show(env[v] == env[w])}')
    prog.append('print(a, b, c)')
    prog.append('print(m)')
    prog.append('print(saved)')
    out.append(f"{show(env['a'])} {show(env['b'])} {show(env['c'])}")
    out.append(show(env['m']))
    out.append(show(env['saved']))
    return prog, out


def main():
    mode, n = sys.argv[1], int(sys.argv[2])
    prog, out = gen(n)
    lines = prog if mode == '--program' else out
    sys.stdout.write(''.join(l + '\n' for l in lines))


main()
