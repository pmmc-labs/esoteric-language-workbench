#!/usr/bin/env python3
"""Model for golden test 100-arith: Strata's number arithmetic and comparison.

The program is `print` lines over edge values (0, +-1, +-2, +-7, the 64-bit
limits, values near overflow, powers of two) for every binary operator, and
prefix minus on each value. The expected output is computed from Python
integers by the definition in LANGUAGE.md and D19/D20: `/` truncates toward
zero, `%` has the sign of its left operand (Python's `//` and `%` floor, so
they are not used), comparisons give 1 or 0. A line whose result doesn't fit
in 64 bits, or which divides by zero, is left out of the program: those are
the fault tests 105 to 110 and 113, one fault per test.

    python3 t/models/arith.py --program > t/100-arith.strata
    python3 t/models/arith.py > t/100-arith.expected
"""
import sys

MIN, MAX = -(2**63), 2**63 - 1
VALUES = [0, 1, -1, 2, -2, 7, -7, MAX, MAX - 1, -MAX, MIN, 3037000499, -3037000499,
          2**62, -(2**62), 2**32, -(2**32)]


def lit(v):
    # The minimum can't be written as a literal (D19); compute it.
    if v == MIN:
        return "(-9223372036854775807 - 1)"
    return str(v)  # a negative value is prefix minus on a literal


def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def tmod(a, b):
    return a - b * tdiv(a, b)


OPS = {
    "+": lambda a, b: a + b,
    "-": lambda a, b: a - b,
    "*": lambda a, b: a * b,
    "/": lambda a, b: None if b == 0 else tdiv(a, b),
    # D19: the minimum % -1 is an overflow too, so % agrees with /.
    "%": lambda a, b: None if b == 0 or (a == MIN and b == -1) else tmod(a, b),
    "=": lambda a, b: int(a == b),
    "!=": lambda a, b: int(a != b),
    "<": lambda a, b: int(a < b),
    "<=": lambda a, b: int(a <= b),
    ">": lambda a, b: int(a > b),
    ">=": lambda a, b: int(a >= b),
}


def lines():
    for op, f in OPS.items():
        for a in VALUES:
            for b in VALUES:
                r = f(a, b)
                if r is not None and MIN <= r <= MAX:
                    yield f"print {lit(a)} {op} {lit(b)}", r
    for a in VALUES:
        if -a <= MAX:
            yield f"print -{lit(a)}" if a != MIN else None, -a


if __name__ == "__main__":
    rows = [(t, r) for t, r in lines() if t]
    if "--program" in sys.argv:
        print("; Generated by t/models/arith.py --program; do not edit.")
        for t, _ in rows:
            print(t)
    else:
        for _, r in rows:
            print(r)
