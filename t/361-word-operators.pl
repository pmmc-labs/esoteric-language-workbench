# not, and, or and xor, which bind more loosely than say and than the
# comma: here each is inside brackets (D51).
use v5.42;
say(0 or 2);
say(1 and 2);
say("[" . (1 xor 1) . "]");
say(0 xor 5);
say(5 xor 0);
say(1 or 0 and 0);
say("[" . (0 or 1 xor 1) . "]");
say(1 xor 0 or 0);
say(0 and 1 or 2);
say(1 or 2 and 3);
say("[" . (not 1) . "]");
say(not 0);
say("[" . (not 0 || 1) . "]");
say("[" . (not 1 or 0) . "]");
say(not 1 or 1);
say("[" . (not 1 and 0) . "]");
say("[" . (not 1 == 1) . "]");
say("[" . (not 1 ? 2 : 3) . "]");
say(! 1 ? 2 : 3);
say(not not 1);
say("[" . (not not 0) . "]");
say(1 and not 0);
say(1 && not 0);
say(1 + not 0);
say(1 + not 0 || 1);
say(- not 0);
say("[" . (! not 0) . "]");
say(not(0));
say(not (0));
say("[" . (not (1)) . "]");
say(not (0) and 2);
say(not (1) or 3);
say(not (0) xor 0);
say((not 0) || 1);
say((not 0) + 1);
say((not 1) . "a");
say(1 ? 2 : 3 or 4);
say(0 ? 2 : 0 or 4);
say(1 == 1 and 2 == 2);
say(1 || 0 and 0 || 3);
say(undef or 1);
say(undef xor 1);
say("[" . (undef and 1 or 2) . "]");
say substr("abcdef", (not 0), 1);
say substr("abcdef", not(0), 1);
say index("abcabc", "c", (0 or 3));
say substr("abcdef", 0 || 2, 1 && 2);
say substr("abcdef", 1 ? 2 : 3, !0 + 1);
say length(not 1);
say defined(not 1);
say(not
    0);
