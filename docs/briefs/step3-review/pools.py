def numstrings(full=True):
    """Python strings: numeric and near-numeric"""
    out = []
    for body in DIG + DEC + EXP:
        for s in SIGN:
            out.append(s + body)
    if full:
        for body in ['0', '12', '012', '1.0', '1.5', '.5', '1.', '1e3', '1.5e0', '9007199254740992', '9223372036854775807', '-0.0', '-0', '+12', '-12', '-1.0', '+1.0', '-1e3', '-.5']:
            for a in PRE:
                for b in POST:
                    if a or b:
                        out.append(a + body + b)
    out += BAD
    seen = set()
    res = []
    for s in out:
        if s not in seen:
            seen.add(s)
            res.append(s)
    return res

