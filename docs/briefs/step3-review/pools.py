def q(s):
    """a double-quoted literal for the Python string s, escapes as the definition has them"""
    out = []
    for c in s:
        o = ord(c)
        if c in '"\\$@':
            out.append('\\' + c)
        elif 0x20 <= o < 0x7F:
            out.append(c)
        elif c == '\n':
            out.append('\\n')
        elif c == '\t':
            out.append('\\t')
        else:
            out.append('\\x{%X}' % o)
    return '"' + ''.join(out) + '"'

